const I = require('../www/js/insights.js');
let fail = 0;
const ok = (name, c, info) => { if (!c) { fail++; console.log('✗', name, info || ''); } else console.log('✓', name); };
const pad = n => String(n).padStart(2, '0');
const now = new Date(2026, 9, 17, 12);
const ago = n => { const d = new Date(2026, 9, 17 - n); return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`; };
const M = n => `${n} Br`;
let id = 0;
const ex = (cat, amount, a, note = '') => ({ id: 'x' + (++id), type: 'expense', cat, amount, date: ago(a), note });
ok('мало данных: пусто', I.build([ex('Кафе', 5, 0)], now, M).length === 0);
const tx = [0, 1, 2, 3, 4, 5, 6].map(i => ex('Кафе', 6, i, 'кофе')).concat([ex('Продукты', 80, 8), ex('Продукты', 60, 9), ex('Дом', 500, 12), { id: 'i1', type: 'income', cat: 'Зарплата', amount: 2000, date: ago(10), note: '' }]);
const list = I.build(tx, now, M);
ok('есть баннеры', list.length >= 3, list.map(x => x.id).join());
ok('у каждого есть заголовок, текст, цвет и иконка', list.every(x => x.title && x.text && x.tone && x.icon));
ok('привычка «кофе»', list.some(x => x.id === 'habit' && /кофе/.test(x.title)));
ok('крупная трата', list.some(x => x.id === 'biggest' && /500/.test(x.title)));
ok('остаток от дохода', list.some(x => x.id === 'left'));
ok('серия записей', list.some(x => x.id === 'streak'));
ok('выбор двух', I.pick(list, now, 2).length === 2 && I.pick(list, now, 2).every((x, i, a) => a.indexOf(x) === i));
const bad = /(слишком|плохо|нарушени)/i;
ok('в текстах нет запретных слов', list.every(x => !bad.test(x.title + x.text)));
if (fail) { console.log(`\nПровалено: ${fail}`); process.exit(1); } else console.log('\nВсе тесты прошли');
